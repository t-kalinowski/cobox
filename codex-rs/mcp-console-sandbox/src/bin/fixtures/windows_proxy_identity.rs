//! Adversarial token probes used only by the executable acceptance fixture.
use anyhow::Context;
use anyhow::Result;
use anyhow::ensure;
use serde_json::Value;
use serde_json::json;
use std::os::windows::io::AsRawHandle;
use std::os::windows::io::FromRawHandle;
use std::os::windows::io::OwnedHandle;
use windows_sys::Win32::Foundation::*;
use windows_sys::Win32::Security::Authorization::*;
use windows_sys::Win32::Security::*;
use windows_sys::Win32::System::Threading::*;

pub(super) fn restricting_sids() -> Result<Vec<String>> {
    let mut token = std::ptr::null_mut();
    ensure!(
        unsafe { OpenProcessToken(GetCurrentProcess(), TOKEN_QUERY, &mut token) } != 0,
        "open token"
    );
    let token = unsafe { OwnedHandle::from_raw_handle(token) };
    token_restricting_sids(&token)
}

fn token_restricting_sids(token: &OwnedHandle) -> Result<Vec<String>> {
    let mut needed = 0;
    unsafe {
        GetTokenInformation(
            token.as_raw_handle(),
            TokenRestrictedSids,
            std::ptr::null_mut(),
            /*tokeninformationlength*/ 0,
            &mut needed,
        )
    };
    let mut buffer = vec![0_usize; (needed as usize).div_ceil(size_of::<usize>())];
    ensure!(
        unsafe {
            GetTokenInformation(
                token.as_raw_handle(),
                TokenRestrictedSids,
                buffer.as_mut_ptr().cast(),
                needed,
                &mut needed,
            )
        } != 0,
        "read restricting SIDs"
    );
    let groups = unsafe { &*buffer.as_ptr().cast::<TOKEN_GROUPS>() };
    let mut result = Vec::new();
    for entry in
        unsafe { std::slice::from_raw_parts(groups.Groups.as_ptr(), groups.GroupCount as usize) }
    {
        let mut text = std::ptr::null_mut();
        ensure!(
            unsafe { ConvertSidToStringSidW(entry.Sid, &mut text) } != 0,
            "format SID"
        );
        let mut length = 0;
        while unsafe { *text.add(length) } != 0 {
            length += 1;
        }
        let value = unsafe { String::from_utf16(std::slice::from_raw_parts(text, length)) };
        unsafe { LocalFree(text.cast()) };
        result.push(value?);
    }
    Ok(result)
}

pub(super) fn forge(sid: &str, endpoint: &str, destination: &str) -> Result<Value> {
    let route_sid = codex_windows_sandbox::LocalSid::from_string(sid)?;
    let token = unsafe {
        OwnedHandle::from_raw_handle(
            codex_windows_sandbox::get_current_token_for_restriction()? as _
        )
    };
    let original = token_restricting_sids(&token)?;
    // Preserve the user/logon identities needed for native process initialization.
    // A lone route SID can make the child fail before it ever attempts a connection.
    let restricted = if original.iter().any(|value| value == sid) {
        token
    } else if original.is_empty() {
        unsafe {
            OwnedHandle::from_raw_handle(
                codex_windows_sandbox::create_readonly_token_with_caps_and_user_from(
                    token.as_raw_handle() as _,
                    &[route_sid.as_ptr()],
                    &[],
                )? as _,
            )
        }
    } else {
        let sids = original
            .iter()
            .map(|sid| codex_windows_sandbox::LocalSid::from_string(sid))
            .collect::<Result<Vec<_>>>()?;
        let restrictions = sids
            .iter()
            .chain(std::iter::once(&route_sid))
            .map(|sid| SID_AND_ATTRIBUTES {
                Sid: sid.as_ptr(),
                Attributes: 0,
            })
            .collect::<Vec<_>>();
        let mut restricted = std::ptr::null_mut();
        ensure!(
            unsafe {
                CreateRestrictedToken(
                    token.as_raw_handle(),
                    /*flags*/ 0,
                    /*disablesidcount*/ 0,
                    std::ptr::null(),
                    /*deleteprivilegecount*/ 0,
                    std::ptr::null(),
                    restrictions.len() as u32,
                    restrictions.as_ptr(),
                    &mut restricted,
                )
            } != 0,
            "re-restrict attacker token: {}",
            std::io::Error::last_os_error()
        );
        unsafe { OwnedHandle::from_raw_handle(restricted) }
    };
    if !token_restricting_sids(&restricted)?
        .iter()
        .any(|value| value == sid)
    {
        ensure!(
            !original.is_empty() && !original.iter().any(|value| value == sid),
            "requested route SID unexpectedly absent from forged token"
        );
        // Windows intersects restrictions when re-restricting an existing token.
        return Ok(json!({"identity_created":false, "reason":"restricting-sid-intersection"}));
    }
    // Inputs are generated by the test and contain no quotes. The executable path may contain spaces.
    let command = format!(
        "\"{}\" probe-route {endpoint} {destination}",
        std::env::current_exe()?.display()
    );
    let mut command: Vec<u16> = command.encode_utf16().chain([0]).collect();
    let mut startup: STARTUPINFOW = unsafe { std::mem::zeroed() };
    startup.cb = size_of::<STARTUPINFOW>() as u32;
    let mut process: PROCESS_INFORMATION = unsafe { std::mem::zeroed() };
    ensure!(
        unsafe {
            CreateProcessAsUserW(
                restricted.as_raw_handle(),
                std::ptr::null(),
                command.as_mut_ptr(),
                std::ptr::null(),
                std::ptr::null(),
                /*binherithandles*/ 0,
                CREATE_NO_WINDOW,
                std::ptr::null(),
                std::ptr::null(),
                &startup,
                &mut process,
            )
        } != 0,
        "start forged-route process: {}",
        std::io::Error::last_os_error()
    );
    let child = unsafe { OwnedHandle::from_raw_handle(process.hProcess) };
    let _thread = unsafe { OwnedHandle::from_raw_handle(process.hThread) };
    ensure!(
        unsafe {
            WaitForSingleObject(child.as_raw_handle(), /*dwmilliseconds*/ 10_000)
        } == WAIT_OBJECT_0,
        "forged-route probe timed out"
    );
    let mut code = 0;
    ensure!(
        unsafe { GetExitCodeProcess(child.as_raw_handle(), &mut code) } != 0,
        "probe exit code"
    );
    Ok(json!({"code":code}))
}

pub(super) fn probe_route() -> Result<()> {
    use std::io::ErrorKind;
    use std::io::Read;
    use std::io::Write;
    let endpoint = std::env::args().nth(2).context("endpoint")?;
    let destination = std::env::args().nth(3).context("destination")?;
    // Malformed inputs and socket setup failures must not masquerade as enforcement.
    let endpoint: std::net::SocketAddr = endpoint
        .strip_prefix("http://")
        .unwrap_or(&endpoint)
        .trim_end_matches('/')
        .parse()
        .context("proxy endpoint")?;
    let (host, port) = destination
        .rsplit_once(':')
        .context("destination authority")?;
    ensure!(
        !host.is_empty()
            && !host
                .chars()
                .any(|ch| ch.is_whitespace() || matches!(ch, '/' | '"' | '?' | '#')),
        "invalid destination host"
    );
    let _port: u16 = port.parse().context("destination port")?;
    let timeout = std::time::Duration::from_secs(/*secs*/ 2);
    let mut stream = match std::net::TcpStream::connect_timeout(&endpoint, timeout) {
        Ok(stream) => stream,
        // Account firewall enforcement can deny before the ingress accepts a socket.
        Err(_) => std::process::exit(0),
    };
    stream.set_read_timeout(Some(timeout))?;
    stream.set_write_timeout(Some(timeout))?;
    if let Err(error) = write!(
        stream,
        "GET http://{destination}/ HTTP/1.1\r\nHost: {destination}\r\nConnection: close\r\n\r\n"
    ) {
        match error.kind() {
            ErrorKind::ConnectionReset | ErrorKind::ConnectionAborted | ErrorKind::BrokenPipe => {
                std::process::exit(0);
            }
            _ => return Err(error).context("send route request"),
        }
    }
    let mut response = Vec::new();
    let mut buffer = [0; 1024];
    loop {
        match stream.read(&mut buffer) {
            Ok(0) => break,
            Ok(count) => response.extend_from_slice(&buffer[..count]),
            Err(error)
                if response.is_empty()
                    && matches!(
                        error.kind(),
                        ErrorKind::ConnectionReset | ErrorKind::ConnectionAborted
                    ) =>
            {
                break;
            }
            Err(error) => return Err(error).context("read route response"),
        }
        ensure!(
            response.len() <= 16384,
            "route response exceeds probe limit"
        );
    }
    // Account/route admission rejects the connection before starting HTTP.
    if response.is_empty() {
        std::process::exit(0);
    }
    let end = response
        .windows(4)
        .position(|bytes| bytes == b"\r\n\r\n")
        .context("truncated route response headers")?;
    let headers = std::str::from_utf8(&response[..end])?;
    let mut lines = headers.split("\r\n");
    let status = lines.next().context("route response status")?;
    let status = status
        .strip_prefix("HTTP/1.1 ")
        .context("invalid route response status")?
        .split(' ')
        .next()
        .context("route response code")?;
    let mut length = None;
    for line in lines {
        let (name, value) = line
            .split_once(':')
            .context("invalid route response header")?;
        ensure!(
            !name.eq_ignore_ascii_case("transfer-encoding"),
            "unsupported route response encoding"
        );
        if name.eq_ignore_ascii_case("content-length") {
            ensure!(length.is_none(), "duplicate route content length");
            length = Some(
                value
                    .trim()
                    .parse::<usize>()
                    .context("route content length")?,
            );
        }
    }
    ensure!(
        length.is_none_or(|length| length == response.len() - end - 4),
        "truncated route response body"
    );
    match status {
        "200" => std::process::exit(91),
        "403" => std::process::exit(0),
        _ => anyhow::bail!("unexpected route response status: {status}"),
    }
}
